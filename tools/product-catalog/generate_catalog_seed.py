"""Generates mdlsource/24b-product-catalog-seed.mdl from products.ttl.

The Turtle file is the seed of the product catalog in the app database: the
app owns the data (24-product-catalog.mdl) and the runtime serves it as
RDF again. Reads the file with DuckDB's rdf extension.

Run:  python3 tools/product-catalog/generate_catalog_seed.py   (needs: pip install duckdb)
"""
import os
from collections import defaultdict

import duckdb

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
SHOP = "https://example.org/bikeshop#"
RDFS = "http://www.w3.org/2000/01/rdf-schema#"
TYPE = "http://www.w3.org/1999/02/22-rdf-syntax-ns#type"
KINDS = {"Bike": "Bike", "EBike": "EBike", "Part": "Part", "Accessory": "Accessory"}

con = duckdb.connect()
con.sql("INSTALL rdf FROM community; LOAD rdf")
rows = con.execute("SELECT subject, predicate, object FROM read_rdf(?, prefix_expansion = true)", [os.path.join(HERE, "products.ttl")]).fetchall()
facts = defaultdict(lambda: defaultdict(list))
for s, p, o in rows:
    facts[s][p.replace(SHOP, "shop:").replace(RDFS, "rdfs:").replace(TYPE, "a")].append(o)


def local(iri: str) -> str:
    return iri.replace(SHOP, "")


def q(text) -> str:
    return "'" + str(text).replace("'", "''") + "'" if text not in (None, "") else "empty"


def one(f, key):
    return f[key][0] if f.get(key) else None


def of_type(cls):
    return [s for s, f in facts.items() if SHOP + cls in f.get("a", [])]


out = ["mdl 1;", "", "-- GENERATED by tools/product-catalog/generate_catalog_seed.py from products.ttl: do not edit by hand.", ""]

suppliers = sorted(of_type("Supplier"))
products = sorted((s for c in KINDS for s in of_type(c)), key=lambda s: one(facts[s], "shop:sku"))
calls = []  # one helper call per fact group, in dependency order: suppliers, products, links, issues, lines
for s in suppliers:
    f = facts[s]
    calls.append(f'call microflow "ServiceDesk"."SUB_Supplier_SeedOne" (Code = {q(local(s))}, Name = {q(one(f, "rdfs:label"))}, Country = {q(one(f, "shop:country"))});')
for s in products:
    f = facts[s]
    kind = next(KINDS[c.replace(SHOP, "")] for c in f["a"] if c.replace(SHOP, "") in KINDS)
    calls.append(
        f'call microflow "ServiceDesk"."SUB_Product_SeedOne" (Sku = {q(one(f, "shop:sku"))}, Name = {q(one(f, "rdfs:label"))}, Kind = ServiceDesk.ENUM_ProductKind.{kind}, '
        f'Price = {one(f, "shop:price")}, WarrantyYears = {one(f, "shop:warrantyYears")}, SupplierCode = {q(local(one(f, "shop:suppliedBy")))}, '
        f'WheelSize = {q(one(f, "shop:wheelSize"))}, SeatPostDiameter = {q(one(f, "shop:seatPostDiameter"))}, Brakes = {q(one(f, "shop:brakes"))}, RackMount = {"true" if one(f, "shop:rackMount") == "true" else "false"});')
for s in products:
    f = facts[s]
    for key, comp in (("shop:hasComponent", "true"), ("shop:compatibleWith", "false")):
        for t in sorted(f.get(key, [])):
            calls.append(f'call microflow "ServiceDesk"."SUB_Product_SeedLink" (FromSku = {q(one(f, "shop:sku"))}, ToSku = {q(one(facts[t], "shop:sku"))}, IsComponent = {comp});')
for s in sorted(of_type("KnownIssue") + of_type("Recall")):
    f = facts[s]
    calls.append(f'call microflow "ServiceDesk"."SUB_KnownIssue_SeedOne" (IssueId = {q(one(f, "shop:issueId"))}, Title = {q(one(f, "rdfs:label"))}, IsRecall = {"true" if SHOP + "Recall" in f["a"] else "false"}, '
                 f'AffectsBatch = {q(one(f, "shop:affectsBatch"))}, Announced = parseDateTimeUTC({q(one(f, "shop:announced"))}, \'yyyy-MM-dd\'), Advice = {q(one(f, "shop:advice"))}, Sku = {q(one(facts[one(f, "shop:affects")], "shop:sku"))});')
for s in sorted(of_type("Order"), key=lambda s: one(facts[s], "shop:orderNumber")):
    f = facts[s]
    for ln in f.get("shop:hasLine", []):
        lf = facts[ln]
        calls.append(f'call microflow "ServiceDesk"."SUB_OrderLine_SeedOne" (OrderNumber = {q(one(f, "shop:orderNumber"))}, Sku = {q(one(facts[one(lf, "shop:product")], "shop:sku"))}, '
                     f'Quantity = {one(lf, "shop:quantity")}, UnitPrice = {one(lf, "shop:unitPrice")}, Batch = {q(one(lf, "shop:batch"))});')

BATCH = 20  # activities per microflow, under the lint limit
batches = [calls[i:i + BATCH] for i in range(0, len(calls), BATCH)]
for n, batch in enumerate(batches, 1):
    out.append(f"/** Seeds part {n} of {len(batches)} of the product catalog. Generated. */")
    out.append(f'create or modify microflow "ServiceDesk"."SUB_ProductCatalog_Seed_{n}" ()\nfolder \'Product catalog\'\nbegin')
    out.extend("  " + c for c in batch)
    out.append("end;\n")

out.append("/** Seeds the product catalog unless it has products already. Generated. */")
out.append('create or modify microflow "ServiceDesk"."SUB_ProductCatalog_Seed" ()\nreturns Boolean as $Seeded\nfolder \'Product catalog\'\nbegin')
out.append('  retrieve $Any from "ServiceDesk"."Product" first;\n  if $Any != empty then\n    return false;\n  end if;')
out.extend(f'  call microflow "ServiceDesk"."SUB_ProductCatalog_Seed_{n}" ();' for n in range(1, len(batches) + 1))
out.append("  log info node 'ServiceDesk' 'Seeded the product catalog.';\n  return true;\nend;")

with open(os.path.join(ROOT, "mdlsource", "24b-product-catalog-seed.mdl"), "w") as fh:
    fh.write("\n".join(out) + "\n")
print("wrote mdlsource/24b-product-catalog-seed.mdl")
